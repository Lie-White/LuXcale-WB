LANGUAGES = ("en", "ko")
_language = "en"
_listeners: list[Callable[[], None]] = []


def tr(key: str, **fmt) -> str:
    text = STRINGS[key][_language]
    return text.format(**fmt) if fmt else text


def language() -> str:
    return _language


def set_language(lang: str) -> None:
    global _language
    if lang not in LANGUAGES:
        raise ValueError(f"unknown language {lang!r}")
    _language = lang
    for fn in list(_listeners):
        fn()


def on_change(fn: Callable[[], None]) -> None:
    """Call `fn` after every language switch (widgets re-apply their text)."""
    _listeners.append(fn)


def bind(widget, key: str, setter: str = "setText") -> None:
    """Set the widget's text from `key` now and after every language switch."""
    def apply():
        getattr(widget, setter)(tr(key))

    apply()
    _listeners.append(apply)
